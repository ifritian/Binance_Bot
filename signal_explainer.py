def _family(strategy: str) -> Optional[str]:
    """Тип стратегии для выбора шаблона (по подстроке названия)."""
    lowered = str(strategy or "").lower()
    if "donchian" in lowered or "breakout" in lowered:
        return "breakout"
    if "macd" in lowered:
        return "momentum"
    if "rsi" in lowered or "bollinger" in lowered or "divergence" in lowered:
        return "reversal"
    return None


def _to_float(value) -> Optional[float]:
    try:
        return float(str(value).replace(",", "").replace("%", "").strip())
    except (TypeError, ValueError):
        return None


def risk_reward_percents(signal) -> tuple:
    """(риск%, прибыль%) относительно середины диапазона входа: расстояние
    до стопа и до тейка. (None, None), если числа не распознались или
    риск нулевой."""
    low, high = _to_float(signal.entry_low), _to_float(signal.entry_high)
    stop, target = _to_float(signal.invalidation), _to_float(signal.target)
    if None in (low, high, stop, target):
        return None, None
    entry = (low + high) / 2
    if entry <= 0:
        return None, None
    risk = abs(entry - stop) / entry * 100
    reward = abs(target - entry) / entry * 100
    if risk <= 0 or reward <= 0:
        return None, None
    return round(risk, 1), round(reward, 1)


def explain_signal(signal, rng: Optional[random.Random] = None) -> str:
    """Объяснение сигнала простыми словами (2-4 предложения). Не падает ни
    на каких данных: если нечего посчитать, отдаёт общую фразу без
    процентов."""
    rng = rng or random
    risk, reward = risk_reward_percents(signal)

    if risk is None:
        body = rng.choice(_NO_PERCENTS)
    else:
        is_long = signal_parser.is_long_direction(signal.direction)
        family = _family(signal.strategy)
        variants = _TEMPLATES.get((family, is_long)) or _GENERIC
        body = rng.choice(variants).format(
            stop=signal.invalidation, target=signal.target, risk=f"{risk:g}", reward=f"{reward:g}",
        )

    return f"{body} {rng.choice(_CLOSING)}"
